export function catalogueForPermissions(permissions: string[]) {
  return REPORT_CATALOGUE.filter(
    (row) => permissions.includes(row.permission) || permissions.includes('reports:read'),
  ).map((row) => ({
    ...row,
    available: row.implemented && (permissions.includes(row.permission) || row.permission === 'reports:read'),
  }));
}
